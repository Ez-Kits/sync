// Columns are named explicitly so a `casing` option cannot rename them.

/**
 * Outbox, dirty-record, applied-event, checkpoint and skipped-event tables of Postgres
 * storages, created by the adapter itself. `seq` is assigned on insert, so pending events
 * follow commit order.
 */
export const pgLocalChangeTables = {
  events: pgTable(
    "ez_sync_events",
    {
      seq: bigint("seq", { mode: "number" }).primaryKey().generatedByDefaultAsIdentity(),
      id: text("id").notNull().unique(),
      type: text("type").notNull(),
      collection: text("collection").notNull(),
      data: jsonb("data"),
      recordId: text("recordId").notNull(),
      createdAt: bigint("createdAt", { mode: "number" }).notNull(),
    },
    (table) => [
      index("ez_sync_events_collection_seq").on(table.collection, table.seq),
      index("ez_sync_events_record").on(table.collection, table.recordId),
    ],
  ),
  dirtyRecords: pgTable(
    "ez_sync_dirty_records",
    {
      collection: text("collection").notNull(),
      recordId: text("recordId").notNull(),
      state: text("state").notNull(),
      updatedAt: bigint("updatedAt", { mode: "number" }).notNull(),
    },
    (table) => [uniqueIndex("ez_sync_dirty_record_key").on(table.collection, table.recordId)],
  ),
  appliedEvents: pgTable(
    "ez_sync_applied_events",
    {
      eventId: text("eventId").primaryKey(),
      appliedAt: bigint("appliedAt", { mode: "number" }).notNull(),
    },
    (table) => [index("ez_sync_applied_events_applied_at").on(table.appliedAt)],
  ),
  checkpoints: pgTable("ez_sync_checkpoints", {
    collection: text("collection").primaryKey(),
    value: text("value").notNull(),
  }),
  skippedRemoteEvents: pgTable(
    "ez_sync_skipped_remote_events",
    {
      collection: text("collection").notNull(),
      recordId: text("recordId").notNull(),
      event: jsonb("event").notNull(),
    },
    (table) => [primaryKey({ columns: [table.collection, table.recordId] })],
  ),
};

const PG_EVENTS_TABLE_DDL = `
CREATE TABLE IF NOT EXISTS ez_sync_events (
  seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id TEXT NOT NULL UNIQUE,
  type TEXT NOT NULL,
  collection TEXT NOT NULL,
  data JSONB,
  "recordId" TEXT NOT NULL,
  "createdAt" BIGINT NOT NULL
);`;

/** Creates and upgrades {@link pgLocalChangeTables}; run by the store's `initialize`. */
const PG_LOCAL_CHANGE_SCHEMA: LocalChangeSchemaScripts = {
  createMeta:
    "CREATE TABLE IF NOT EXISTS ez_sync_meta (key TEXT PRIMARY KEY NOT NULL, value INTEGER NOT NULL)",
  hasEvents:
    "SELECT 1 FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = 'ez_sync_events'",
  create: `${PG_EVENTS_TABLE_DDL}
CREATE INDEX IF NOT EXISTS ez_sync_events_collection_seq ON ez_sync_events (collection, seq);
CREATE INDEX IF NOT EXISTS ez_sync_events_record ON ez_sync_events (collection, "recordId");
CREATE TABLE IF NOT EXISTS ez_sync_dirty_records (
  collection TEXT NOT NULL,
  "recordId" TEXT NOT NULL,
  state TEXT NOT NULL,
  "updatedAt" BIGINT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS ez_sync_dirty_record_key
  ON ez_sync_dirty_records (collection, "recordId");
CREATE TABLE IF NOT EXISTS ez_sync_applied_events (
  "eventId" TEXT PRIMARY KEY,
  "appliedAt" BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS ez_sync_applied_events_applied_at
  ON ez_sync_applied_events ("appliedAt");
CREATE TABLE IF NOT EXISTS ez_sync_checkpoints (
  collection TEXT PRIMARY KEY,
  value TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS ez_sync_skipped_remote_events (
  collection TEXT NOT NULL,
  "recordId" TEXT NOT NULL,
  event JSONB NOT NULL,
  PRIMARY KEY (collection, "recordId")
);
`,
  // The copy sets `seq` itself, so the identity restarts after the copied rows.
  upgradeFromV1: `
CREATE TEMP TABLE ez_sync_events_v1 AS SELECT * FROM ez_sync_events;
DROP TABLE ez_sync_events;
${PG_EVENTS_TABLE_DDL}
INSERT INTO ez_sync_events (seq, id, type, collection, data, "recordId", "createdAt")
  SELECT row_number() OVER (ORDER BY "createdAt", id), id, type, collection, data, "recordId", "createdAt"
  FROM pg_temp.ez_sync_events_v1;
SELECT setval(pg_get_serial_sequence('ez_sync_events', 'seq'), COALESCE(MAX(seq), 0) + 1, false)
  FROM ez_sync_events;
DROP TABLE pg_temp.ez_sync_events_v1;
`,
};

/** Drizzle options of Postgres adapters. `codecs` default to Drizzle's PGlite codecs. */
export type DrizzlePgOptions<TRelations extends AnyRelations> = Omit<
  DrizzlePgConfig<TRelations>,
  "relations"
>;

export type DrizzlePgDBAdapterConfig<
  C extends CollectionConfigMap,
  TRelations extends AnyRelations = BuildRelationsFromCollections<C>,
> = DrizzleProxyDBAdapterConfig<C, TRelations, DrizzlePgOptions<TRelations>>;

/**
 * A Drizzle adapter for Postgres storages (PGlite), through `drizzle-orm/pg-proxy`. The
 * outbox lives in {@link pgLocalChangeTables}.
 */
export function createDrizzlePgDBAdapter<
  C extends CollectionConfigMap,
  TRelations extends AnyRelations = BuildRelationsFromCollections<C>,
>(
  config: DrizzlePgDBAdapterConfig<C, TRelations>,
): DrizzleDBAdapter<C, PgRemoteDatabase<TRelations>, BuildSchemaFromCollections<C>> {
  const drizzleConfig = config.drizzleConfig ?? {};
  return createDrizzleProxyDBAdapter(config, {
    dialect: "postgres",
    createDatabase: (executor, relations: TRelations) =>
      drizzle(
        async (sql, params, method) =>
          executor.exec({
            sql,
            params,
            method: "all",
            rowMode: method === "all" ? "array" : "object",
          }),
        { ...drizzleConfig, relations, codecs: drizzleConfig.codecs ?? pgliteCodecs },
      ),
    createLocalChangeStore: (db, dbStorage) =>
      createDrizzleLocalChangeStore({
        db,
        tables: pgLocalChangeTables,
        initialize: () => initializeLocalChangeSchema(dbStorage, PG_LOCAL_CHANGE_SCHEMA),
      }),
  });
}
